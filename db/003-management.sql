ALTER TABLE project ADD COLUMN IF NOT EXISTS updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6);
CREATE TABLE IF NOT EXISTS app_control (
 control_id TINYINT PRIMARY KEY CHECK(control_id=1),
 setup_digest CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
