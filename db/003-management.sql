ALTER TABLE employee ADD COLUMN IF NOT EXISTS must_change_password BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE employee ADD COLUMN IF NOT EXISTS password_changed_at DATETIME(6) NULL;
CREATE SEQUENCE IF NOT EXISTS seq_project START WITH 1 MAXVALUE 9999 NOCYCLE;
CREATE TABLE IF NOT EXISTS project (
 project_id VARCHAR(12) PRIMARY KEY DEFAULT (CONCAT('PRJ',LPAD(NEXT VALUE FOR seq_project,4,'0'))),
 project_name VARCHAR(100) NOT NULL UNIQUE CHECK(length(trim(project_name))>0),
 is_active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
ALTER TABLE property_unit ADD COLUMN IF NOT EXISTS project_id VARCHAR(12) NULL REFERENCES project(project_id);
ALTER TABLE property_unit ADD COLUMN IF NOT EXISTS archived_at DATETIME(6) NULL;
ALTER TABLE property_unit ADD COLUMN IF NOT EXISTS archive_reason VARCHAR(1000) NULL;
ALTER TABLE access_link ADD COLUMN IF NOT EXISTS revoked_at DATETIME(6) NULL;
